function database = check_database(database)
%CHECK_DATABASE Validate the canonical encounter schema and physical definitions.

required = {'schema_version', 'orbit', 'encounters', 'definition', 'generation', 'provenance'};
assert(all(isfield(database, required)) && database.schema_version == 1, ...
    'orb2ds:Schema', 'Use a canonical schema-1 orbit-Moon database.');
database.orbit = orb2ds.internal.check_orbit(database.orbit);
assert(strcmp(database.definition.local_velocity, 'moon_relative_inertial_in_rth') && ...
    strcmp(database.definition.asymptotic_velocity, 'inbound_kepler_asymptote'), ...
    'orb2ds:Database', 'Unknown encounter velocity definitions.');
entries = database.encounters;
required = {'row_id', 'departure_phase', 'delta_v_km_s', 'duration_days', ...
    'state_entry', 'velocity_local_rth_km_s', 'velocity_infinity_rth_km_s'};
assert(isempty(setxor(fieldnames(entries), required)), 'orb2ds:Schema', ...
    'Incorrect encounter fields.');
count = numel(entries.departure_phase);
validateattributes(entries.departure_phase, {'double'}, ...
    {'size', [count, 1], 'real', 'finite', '>=', 0, '<', 1});
validateattributes(entries.duration_days, {'double'}, ...
    {'size', [count, 1], 'real', 'finite', 'positive'});
for name = {'delta_v_km_s', 'velocity_local_rth_km_s'}
    validateattributes(entries.(name{1}), {'double'}, ...
        {'size', [count, 3], 'real', 'finite'});
end
validateattributes(entries.state_entry, {'double'}, {'size', [count, 6], 'real', 'finite'});
validateattributes(entries.velocity_infinity_rth_km_s, {'double'}, {'size', [count, 3], 'real'});
assert(isequal(entries.row_id, (1:count).'), 'orb2ds:Database', ...
    'Encounter row identifiers must be ordered and unique.');
if count > 0
    model = database.orbit.model;
    distance = vecnorm(entries.state_entry(:, 1:3) - ...
        [(1 - model.mu) * model.distance_km, 0, 0], 2, 2);
    assert(max(abs(distance - model.encounter_radius_km)) < 0.1, ...
        'orb2ds:Database', 'Encounter positions disagree with the declared boundary.');
    [local, asymptote] = orb2ds.internal.moon_asymptote(entries.state_entry, model);
    assert(max(abs(local - entries.velocity_local_rth_km_s), [], 'all') < 1e-10 && ...
        isequal(isnan(asymptote), isnan(entries.velocity_infinity_rth_km_s)), ...
        'orb2ds:Database', 'Encounter velocities disagree with the stored states.');
    finite = isfinite(asymptote);
    assert(all(abs(asymptote(finite) - entries.velocity_infinity_rth_km_s(finite)) < 1e-10), ...
        'orb2ds:Database', 'Incorrect incoming asymptotic velocities.');
end
end

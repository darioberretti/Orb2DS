function options = numerical_options()
%NUMERICAL_OPTIONS Return the complete numerical configuration for orb2ds.
%
% PROTOTYPE:
%   options = orb2ds.defaults.numerical_options()
% OUTPUT:
%   options  Nested numerical settings. No epoch, phase or mission-duration
%            constraint is introduced here. See docs/CONTRACTS.md.

options.integration = struct('relative_tolerance', 1e-13, ...
    'absolute_tolerance', 1e-14);
options.validation = struct('enabled', false, 'require_pass', false, ...
    'position_km', 1e-3, 'velocity_km_s', 1e-6, ...
    'time_days', 1e-7, 'orbit_closure_position_km', 0.01, ...
    'orbit_closure_velocity_km_s', 1e-7);
options.mesh = struct('max_step_days', 0.5);
options.mesh.refinement = struct('from', 'moon_periapsis', ...
    'from_offset_days', -1, 'to', 'earth_periapsis', 'factor', 1);
options.patching = struct('method', 'ballistic', 'n_perigee', 101, 'n_moon', 201, ...
    'start_altitude_km', 1000, 'altitude_factor', 1.1, 'max_altitude_trials', 80, ...
    'speed_tolerance_km_s', 0.05, 'n_candidates', 10, ...
    'lambert_tolerance', 1e-6, 'lambert_iterations', 60, ...
    'max_lambert_days', 20, 'flyby_horizon_days', 5, 'target_iterations', 8, ...
    'time_weight_m_s_day', 0, 'lunar_impulse_weight', 1);
options.solver = struct('run_feasibility', true, 'max_iterations_feasibility', 200, ...
    'max_iterations', 2000, 'max_function_evaluations', 1000000, ...
    'minimum_segment_days', 1e-6, ...
    'constraint_tolerance', 1e-12, 'optimality_tolerance', 1e-8, ...
    'step_tolerance', 1e-12, 'display', 'off');
options.solver.name = 'fmincon';
options.solver.evaluation = 'matlab';
options.solver.constraint_tolerances = struct('time_days', []);
options.solver.constraint_tolerances.dynamics = struct('position_km', [], 'velocity_km_s', []);
options.solver.constraint_tolerances.departure = struct('position_km', [], 'velocity_km_s', []);
options.solver.constraint_tolerances.target = struct('velocity_km_s', []);
options.solver.constraint_tolerances.periapsis = struct('radial_velocity_km_s', []);
options.solver.constraint_tolerances.clearance = struct('altitude_km', []);
options.solver.fmincon = struct('algorithm', 'sqp', 'options', struct());
options.solver.ipopt = struct();
options.solver.casadi = struct();
options.solver.cvodes = struct();
options.database = struct('phases', (0:49) / 50, ...
    'impulses_m_s', linspace(0, 50, 10), ...
    'azimuths_rad', (0:99) * 2 * pi / 100, 'elevations_rad', 0, ...
    'horizon_days', 85);
options.n_starts = 1;
options.output = struct('display', true, 'keep_attempt_solutions', false);
options.output.plot_initial_guess = false;
options.output.plot_nlp_guess = false;
end

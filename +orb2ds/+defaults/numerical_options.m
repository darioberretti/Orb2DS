function options = numerical_options()
%NUMERICAL_OPTIONS Return the complete numerical configuration for orb2ds.
%
% PROTOTYPE:
%   options = orb2ds.defaults.numerical_options()
% OUTPUT:
%   options  Nested numerical settings. No epoch, phase or mission-duration
%            constraint is introduced here. See docs/CONTRACTS.md.

options.integration = struct('relative_tolerance', 1e-13, ...
    'absolute_tolerance', 1e-14);
options.mesh = struct('max_step_days', 0.5);
options.patching = struct('n_perigee', 101, 'n_moon', 201, ...
    'start_altitude_km', 1000, 'altitude_factor', 1.1, 'max_altitude_trials', 80, ...
    'speed_tolerance_km_s', 0.05, 'n_candidates', 10, ...
    'lambert_tolerance', 1e-6, 'lambert_iterations', 60, ...
    'max_lambert_days', 20, 'flyby_horizon_days', 5);
options.solver = struct('run_feasibility', true, 'max_iterations_feasibility', 200, ...
    'max_iterations', 2000, 'max_function_evaluations', 1000000, ...
    'minimum_segment_days', 1e-6, ...
    'constraint_tolerance', 1e-12, 'optimality_tolerance', 1e-8, ...
    'step_tolerance', 1e-12, 'display', 'off');
options.validation = struct('position_tolerance_km', 0.001, ...
    'velocity_tolerance_km_s', 1e-6, 'target_tolerance_km_s', 1e-5, ...
    'altitude_tolerance_km', 0.001, 'time_tolerance_days', 1e-7, ...
    'orbit_closure_position_km', 0.01, 'orbit_closure_velocity_km_s', 1e-7);
options.database = struct('phases', (0:49) / 50, ...
    'impulses_m_s', linspace(0, 50, 10), ...
    'azimuths_rad', (0:99) * 2 * pi / 100, 'elevations_rad', 0, ...
    'horizon_days', 85);
options.n_starts = 1;
options.output = struct('display', true, 'keep_attempt_solutions', false);
end
